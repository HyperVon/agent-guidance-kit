#!/usr/bin/env python3
"""Generate docs/evaluations/SUMMARY.md from docs/evaluations/results/*.json.

Only the latest result per (skill, harness, model, reasoning_effort) is
kept — older runs remain in results/ but do not affect the summary.

Usage:
  python3 scripts/generate_evaluation_summary.py --write   # regenerate
  python3 scripts/generate_evaluation_summary.py --check   # verify fresh
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS_ROOT = ROOT / "docs/evaluations/results"
SUMMARY_PATH = ROOT / "docs/evaluations/SUMMARY.md"
SKILLS_ROOT = ROOT / ".agents/skills"

HEADER_MARKER = (
    "<!-- GENERATED by scripts/generate_evaluation_summary.py — do not hand-edit -->"
)


def parse_timestamp(value: str) -> datetime:
    # ISO-8601, tolerate trailing Z and normalize to UTC
    # Legacy fallback: invalid strings return datetime.min for backward
    # compatibility (test expects this). New code should use
    # try_parse_timestamp for explicit invalid handling.
    try:
        if value.endswith("Z"):
            dt = datetime.fromisoformat(value.replace("Z", "+00:00"))
        else:
            dt = datetime.fromisoformat(value)
        if dt.tzinfo is None:
            dt = dt.replace(tzinfo=timezone.utc)
        else:
            dt = dt.astimezone(timezone.utc)
        return dt
    except ValueError:
        return datetime.min.replace(tzinfo=timezone.utc)


def try_parse_timestamp(value: str) -> datetime | None:
    try:
        if value.endswith("Z"):
            dt = datetime.fromisoformat(value.replace("Z", "+00:00"))
        else:
            dt = datetime.fromisoformat(value)
        if dt.tzinfo is None:
            dt = dt.replace(tzinfo=timezone.utc)
        else:
            dt = dt.astimezone(timezone.utc)
        return dt
    except ValueError:
        return None


def load_results() -> list[dict]:
    records: list[dict] = []
    if not RESULTS_ROOT.is_dir():
        return records
    for path in sorted(RESULTS_ROOT.glob("*.json")):
        if path.is_symlink():
            continue
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except (json.JSONDecodeError, OSError, UnicodeDecodeError):
            continue

        if not isinstance(data, dict):
            continue
        run_id = data.get("run_id", "")
        timestamp = data.get("timestamp", "")
        harness = data.get("harness") if isinstance(data.get("harness"), dict) else {}
        model = data.get("model") if isinstance(data.get("model"), dict) else {}
        baseline = data.get("baseline", "")
        skills = data.get("skills") if isinstance(data.get("skills"), list) else []
        harness_name = (
            harness.get("name", "") if isinstance(harness.get("name"), str) else ""
        )
        harness_version = (
            harness.get("version", "")
            if isinstance(harness.get("version"), str)
            else ""
        )
        model_provider = (
            model.get("provider", "") if isinstance(model.get("provider"), str) else ""
        )
        model_name = model.get("name", "") if isinstance(model.get("name"), str) else ""
        reasoning_effort = (
            model.get("reasoning_effort", "")
            if isinstance(model.get("reasoning_effort"), str)
            else ""
        )
        parsed_ts = (
            try_parse_timestamp(timestamp) if isinstance(timestamp, str) else None
        )
        ts = (
            parsed_ts
            if parsed_ts is not None
            else datetime.min.replace(tzinfo=timezone.utc)
        )
        ts_invalid = (
            parsed_ts is None and isinstance(timestamp, str) and timestamp.strip() != ""
        )
        for entry in skills:
            if not isinstance(entry, dict):
                continue
            skill_name = entry.get("skill_name", "")
            if not isinstance(skill_name, str) or not skill_name:
                continue
            cases = entry.get("cases") if isinstance(entry.get("cases"), list) else []
            total_assertions = 0
            skill_pass = 0
            baseline_pass = 0
            any_better = False
            for c in cases:
                if not isinstance(c, dict):
                    continue
                total = c.get("assertions_total", 0)
                sp = c.get("skill_pass", 0)
                bp = c.get("baseline_pass", 0)
                better = c.get("better", False)
                if isinstance(total, int):
                    total_assertions += total
                if isinstance(sp, int):
                    skill_pass += sp
                if isinstance(bp, int):
                    baseline_pass += bp
                if better is True:
                    any_better = True
            decision = entry.get("decision", "")
            overall_better = entry.get("overall_better", any_better)
            measurement_status = entry.get("measurement_status", "legacy")
            # Dedup key: skill × harness × model × effort
            key = (
                skill_name,
                harness_name,
                model_provider,
                model_name,
                reasoning_effort,
            )
            records.append(
                {
                    "key": key,
                    "skill_name": skill_name,
                    "harness_name": harness_name,
                    "harness_version": harness_version,
                    "model_provider": model_provider,
                    "model_name": model_name,
                    "reasoning_effort": reasoning_effort,
                    "run_id": run_id if isinstance(run_id, str) else "",
                    "timestamp": timestamp if isinstance(timestamp, str) else "",
                    "timestamp_dt": ts,
                    "timestamp_invalid": ts_invalid,
                    "baseline": baseline if isinstance(baseline, str) else "",
                    "cases": len(cases),
                    "total_assertions": total_assertions,
                    "skill_pass": skill_pass,
                    "baseline_pass": baseline_pass,
                    "overall_better": overall_better
                    if isinstance(overall_better, bool)
                    else any_better,
                    "decision": decision if isinstance(decision, str) else "",
                    "measurement_status": measurement_status
                    if isinstance(measurement_status, str)
                    else "legacy",
                    "file": path.name,
                    "file_path": path,
                    "harness_label": f"{harness_name} {harness_version}".strip()
                    if harness_version
                    else harness_name,
                    "model_label": model_name
                    + (f" ({reasoning_effort})" if reasoning_effort else ""),
                }
            )
    return records


def latest_per_key(records: list[dict]) -> dict[tuple, dict]:
    latest: dict[tuple, dict] = {}
    for rec in records:
        key = rec["key"]
        cur = latest.get(key)
        if cur is None:
            latest[key] = rec
            continue
        # Compare timestamp, then run_id
        if rec["timestamp_dt"] > cur["timestamp_dt"]:
            latest[key] = rec
        elif (
            rec["timestamp_dt"] == cur["timestamp_dt"] and rec["run_id"] > cur["run_id"]
        ):
            latest[key] = rec
    return latest


def count_skills() -> int:
    if not SKILLS_ROOT.is_dir():
        return 0
    return sum(
        1
        for p in SKILLS_ROOT.iterdir()
        if p.is_dir() and not p.name.startswith(".") and not p.is_symlink()
    )


def generate_summary_text() -> str:
    records = load_results()
    latest = latest_per_key(records)
    skills_count = count_skills()
    results_files = sorted(RESULTS_ROOT.glob("*.json")) if RESULTS_ROOT.is_dir() else []

    # Coverage per skill (latest wins across harnesses? For header we count distinct skills with any latest)
    distinct_skills = {k[0] for k in latest.keys()}

    # Group by harness/model for matrix-like header
    # For rendering table we sort by skill_name then harness/model
    sorted_latest = sorted(
        latest.values(),
        key=lambda r: (
            r["skill_name"],
            r["harness_name"],
            r["model_name"],
            r["reasoning_effort"],
        ),
    )

    lines: list[str] = []
    lines.append(HEADER_MARKER)
    lines.append("# Evaluation Summary")
    lines.append("")
    lines.append(
        "Auto-generated aggregate of the **latest** evaluation result per `(skill, harness, model)` — older runs remain in `docs/evaluations/results/` and `docs/evaluations/*.md` for history, but this file shows only the current head per key so it is easy to scan overall health."
    )
    lines.append("")
    lines.append(
        "Integrity note: new comparisons require separate fresh `WITH-SKILL` and `BASELINE` workers or harness sessions with verifiable skill loading/absence; a role-played no-skill baseline is invalid. Historical result files may be structurally valid without proving that boundary."
    )
    lines.append("")
    lines.append(
        f"_Generated from {len(results_files)} result file(s) in `docs/evaluations/results/`; {len(records)} skill-records considered, {len(latest)} latest entries retained (dedup key: skill × harness × model × reasoning_effort)._"
    )
    # Surface silently skipped invalid/unreadable files (load_results continues on
    # JSON errors; validate_repository flags them, but summary should also warn)
    files_with_records = {r["file"] for r in records}
    skipped_files = [p.name for p in results_files if p.name not in files_with_records]
    # Symlinked files are skipped by load_results but present on disk; count them
    # as skipped as well even though they are not in results_files glob? glob
    # follows symlinks depending on filesystem, but we treat any non-record file as skipped
    if skipped_files:
        lines.append(
            f"_Note: `{len(skipped_files)}` file(s) were skipped as invalid/unreadable and do not contribute to the latest set (see history table for `_invalid_` rows)._"
        )
    lines.append("")
    lines.append(
        "Human interface: ask the agent to \u201crun evals\u201d or \u201cupdate the eval summary\u201d \u2014 the agent runs `python3 scripts/generate_evaluation_summary.py --write` and `make check` (or `--check`). You do not need to run scripts manually; the agent keeps this file fresh and validated."
    )
    lines.append("")

    # Current coverage
    lines.append("## Current coverage")
    lines.append("")
    lines.append(
        f"* Validated skills: `{skills_count}` (`{len(distinct_skills)}/{skills_count}` with at least one executed result in the latest set)."
    )
    lines.append(
        f"* Result files: `{len(results_files)}` JSON + companions in `docs/evaluations/results/`."
    )
    if results_files:
        lines.append(
            f"* Files: {', '.join(f'`{p.name}`' for p in sorted(results_files))}"
        )
    # Timestamp range
    if latest:
        newest = max(r["timestamp_dt"] for r in latest.values())
        oldest = min(r["timestamp_dt"] for r in latest.values())
        # Format without trying to handle exotic timezones too precisely
        lines.append(
            f"* Latest window: `{oldest.isoformat()}` → `{newest.isoformat()}`."
        )
        invalid_count = sum(1 for r in latest.values() if r.get("timestamp_invalid"))
        if invalid_count:
            lines.append(
                f"* Warning: `{invalid_count}` latest entry(s) have an invalid timestamp that was treated as the oldest value; fix the result file(s)."
            )
    lines.append(
        "* Deduplication: latest per `(skill, harness, model, reasoning_effort)` by ISO timestamp, then `run_id`."
    )
    lines.append("")

    # Main table
    lines.append("## Latest per skill × harness × model")
    lines.append("")
    lines.append(
        "`Better` means `overall_better` (`any(case.better)`) and `skill_pass > baseline_pass` on at least one case. `?` means a valid comparison was non-discriminating or inconclusive; it is not evidence that the skill failed. `Decision` and `Measurement` come from the result file."
    )
    lines.append("")
    lines.append(
        "| Skill | Harness | Model | Run ID | Date | Cases | Skill pass | Baseline pass | Better | Measurement | Decision | Source |"
    )
    lines.append(
        "| :--- | :--- | :--- | :--- | :--- | ---: | ---: | ---: | :---: | :--- | :--- | :--- |"
    )
    if not sorted_latest:
        lines.append("| _none_ | – | – | – | – | – | – | – | – | – | – | – |")
    else:
        for r in sorted_latest:
            harness_cell = r["harness_label"] or "–"
            model_cell = r["model_label"] or "–"
            # Date only (YYYY-MM-DD) from timestamp
            date = r["timestamp"][:10] if r["timestamp"] else "–"
            better = (
                "?"
                if r["measurement_status"] in {"inconclusive", "non_discriminating"}
                else "✓"
                if r["overall_better"]
                else "–"
            )
            decision = f"`{r['decision']}`" if r["decision"] else "–"
            measurement = r["measurement_status"] or "–"
            source = f"[{r['file']}](results/{r['file']})"
            # Human companion expected same basename .md
            md_name = r["file"].replace(".json", ".md")
            md_path = RESULTS_ROOT / md_name
            if md_path.is_file():
                source += f" · [human](results/{md_name})"
            lines.append(
                f"| `{r['skill_name']}` | {harness_cell} | {model_cell} | `{r['run_id']}` | {date} | {r['cases']} | {r['skill_pass']}/{r['total_assertions']} | {r['baseline_pass']}/{r['total_assertions']} | {better} | `{measurement}` | {decision} | {source} |"
            )
    lines.append("")

    # Per-skill totals for the primary harness (muse code) if present
    lines.append("## Totals (latest set)")
    lines.append("")
    if sorted_latest:
        total_cases = sum(r["cases"] for r in sorted_latest)
        total_skill = sum(r["skill_pass"] for r in sorted_latest)
        total_base = sum(r["baseline_pass"] for r in sorted_latest)
        total_assert = sum(r["total_assertions"] for r in sorted_latest)
        better_count = sum(1 for r in sorted_latest if r["overall_better"])
        lines.append(f"* Entries: `{len(sorted_latest)}`")
        lines.append(
            f"* Cases: `{total_cases}` — assertions `{total_skill}/{total_assert}` skill pass, `{total_base}/{total_assert}` baseline pass."
        )
        lines.append(
            f"* Better: `{better_count}/{len(sorted_latest)}` entries where `overall_better=true` (skill outperformed baseline)."
        )
        inconclusive_count = sum(
            1
            for r in sorted_latest
            if r["measurement_status"] in {"inconclusive", "non_discriminating"}
        )
        lines.append(
            f"* Inconclusive: `{inconclusive_count}/{len(sorted_latest)}` entries with a valid but non-discriminating measurement."
        )
    else:
        lines.append("* No executed results yet.")
    lines.append("")

    lines.append("## All result files (history)")
    lines.append("")
    lines.append("| File | Run ID | Timestamp | Harness | Model | Baseline | Skills |")
    lines.append("| :--- | :--- | :--- | :--- | :--- | :--- | ---: |")
    if not results_files:
        lines.append("| _none_ | – | – | – | – | – | – |")
    else:
        for path in sorted(results_files):
            try:
                data = json.loads(path.read_text(encoding="utf-8"))
            except (json.JSONDecodeError, OSError, UnicodeDecodeError):
                lines.append(f"| `{path.name}` | _invalid_ | – | – | – | – | – |")
                continue

            if not isinstance(data, dict):
                lines.append(f"| `{path.name}` | _invalid_ | – | – | – | – | – |")
                continue
            run_id = data.get("run_id", "")
            ts = data.get("timestamp", "")
            harness = data.get("harness", {})
            model = data.get("model", {})
            baseline = data.get("baseline", "")
            h = (
                f"{harness.get('name', '')} {harness.get('version', '')}".strip()
                if isinstance(harness, dict)
                else ""
            )
            m = f"{model.get('name', '')}"
            if isinstance(model, dict) and model.get("reasoning_effort"):
                m += f" ({model.get('reasoning_effort')})"
            skills_list = data.get("skills", [])
            lines.append(
                f"| `{path.name}` | `{run_id}` | {ts} | {h or '–'} | {m or '–'} | {baseline or '–'} | {len(skills_list) if isinstance(skills_list, list) else '–'} |"
            )
    lines.append("")

    lines.append("## How to update")
    lines.append("")
    lines.append(
        "Human interface: ask the agent — the agent performs all steps below; you do not need to run scripts manually."
    )
    lines.append("")
    lines.append(
        "1. Agent adds a new result file `docs/evaluations/results/YYYY-MM-DD-<model>-<harness>.json` and its `*.md` companion per [`docs/evaluations/results/README.md`](results/README.md)."
    )
    lines.append(
        "2. Agent runs `python3 scripts/generate_evaluation_summary.py --write` to regenerate this file."
    )
    lines.append(
        "3. Agent runs `make check` — `scripts/validate_repository.py` verifies that `SUMMARY.md` is fresh and that matrix links resolve."
    )
    lines.append("")

    lines.append("## Relation to other docs")
    lines.append("")
    lines.append("* Definitions: `.agents/skills/<name>/evals/evals.json`")
    lines.append(
        "* Matrix (per-cell history): [`docs/evaluations/validation-matrix.md`](validation-matrix.md)"
    )
    lines.append(
        "* Results: [`docs/evaluations/results/`](results/) — machine-readable `*.json` + human `*.md`"
    )
    lines.append(
        "* This summary: `docs/evaluations/SUMMARY.md` (latest per key, auto-generated)"
    )
    lines.append("")

    # Link hygiene: ensure we reference files correctly relative to docs/evaluations/
    text = "\n".join(lines)
    if not text.endswith("\n"):
        text += "\n"
    return text


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate or check evaluation summary")
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true", help="Regenerate SUMMARY.md")
    group.add_argument(
        "--check", action="store_true", help="Check that SUMMARY.md is up to date"
    )
    args = parser.parse_args()

    text = generate_summary_text()
    if args.write:
        SUMMARY_PATH.parent.mkdir(parents=True, exist_ok=True)
        SUMMARY_PATH.write_text(text, encoding="utf-8")
        print(f"Wrote {SUMMARY_PATH.relative_to(ROOT)} ({len(text)} bytes)")
        return 0
    if args.check:
        if not SUMMARY_PATH.is_file():
            print(
                f"ERROR {SUMMARY_PATH.relative_to(ROOT)}: missing — run scripts/generate_evaluation_summary.py --write",
                file=sys.stderr,
            )
            return 1
        existing = SUMMARY_PATH.read_text(encoding="utf-8")
        if existing != text:
            print(
                f"ERROR {SUMMARY_PATH.relative_to(ROOT)}: stale — run scripts/generate_evaluation_summary.py --write",
                file=sys.stderr,
            )
            # Show diff hint without dumping full file
            import difflib

            diff = difflib.unified_diff(
                existing.splitlines()[:20],
                text.splitlines()[:20],
                fromfile="existing",
                tofile="expected",
                lineterm="",
            )
            for line in diff:
                print(line, file=sys.stderr)
            return 1
        print(f"{SUMMARY_PATH.relative_to(ROOT)} is fresh")
        return 0
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
