"""Generate Promptfoo routing test cases from the canonical AGK corpus.

Reads evaluations/confusion-sets/*.json or evaluations/holdout/*.json and
emits a Promptfoo tests YAML file with one test per (case x repetition).
The catalog is generated from current skill frontmatter via the canonical
``scripts/build_routing_catalog.py`` implementation; prompts are composed
byte-identically to v1's neutral-router prompt.

Development sets and holdouts are generated by separate invocations and land
in separate files so they can never be pooled into one score.
"""
import argparse
import json
import os
import sys

_REPO_ROOT = os.path.abspath(os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))
if _REPO_ROOT not in sys.path:
    sys.path.insert(0, _REPO_ROOT)

from experiments.promptfoo.lib import hashing  # noqa: E402
from experiments.promptfoo.lib.paths import (  # noqa: E402
    CONFUSION_SETS,
    GENERATED_DIR,
    HOLDOUTS,
)
from scripts.build_routing_catalog import build  # noqa: E402
from scripts.run_catalog_routing_eval import (  # noqa: E402
    build_confusion_prompt,
)

YAML_HEADER = """\
GENERATED FILE - do not edit by hand.
Source: {source} ({source_hash})
Regenerate: python3 generators/routing_cases.py --set {set_name} --reps {reps}
Corpus stays canonical; this file only projects it into Promptfoo form.
"""


NULL_SENTINEL = "@null"


def _expected(case):
    value = case.get("expected_skill")
    return NULL_SENTINEL if value is None else value


def render_catalog(rows):
    lines = ["Available skills (name — one-line purpose):"]
    for name, desc in rows:
        lines.append(f"- {name} — {desc}")
    return "\n".join(lines)


def case_to_test(case, rep, catalog_text, catalog_names, skills):
    cid = case["id"]
    case_type = case.get("case_type")
    turns = case.get("turns")
    is_workflow = bool(turns) and case_type in (
        "workflow-transition", "harness-native")

    def assertion(fn_name):
        return {"type": "python",
                "value": f"file://../assertions/protocol.py:{fn_name}"}

    if is_workflow:
        turn_payloads = [{
            "prompt": build_confusion_prompt(
                catalog_text, turn.get("user", ""), skills),
            "expected_route": turn.get("expected_route"),
        } for turn in turns]
        return {
            "description": f"case {cid} [{case_type}] workflow rep {rep}",
            "vars": {
                "case_id": cid,
                "rep": rep,
                "case_type": case_type,
                "turns_json": json.dumps(turn_payloads, ensure_ascii=False),
                "catalog_names_json": json.dumps(sorted(catalog_names)),
                "expected_skill": _expected(case),
            },
            "assert": [assertion("check_route_turns")],
        }

    prompt = build_confusion_prompt(catalog_text, case.get("prompt", ""),
                                    skills)
    return {
        "description": f"case {cid} [{case_type}] rep {rep}",
        "vars": {
            "case_id": cid,
            "rep": rep,
            "case_type": case_type,
            "prompt": prompt,
            "catalog_names_json": json.dumps(sorted(catalog_names)),
            "expected_skill": _expected(case),
        },
        "assert": [assertion("check_route_decision")],
    }


def generate(set_name, reps, out_path):
    if set_name in CONFUSION_SETS:
        source_path = CONFUSION_SETS[set_name]
        evidence_kind = "confusion-set"
    elif set_name in HOLDOUTS:
        source_path = HOLDOUTS[set_name]
        evidence_kind = "holdout"
    else:
        raise SystemExit(f"unknown routing set: {set_name}")
    data = json.load(open(source_path))
    skills = data.get("skills") or []
    catalog_rows = [row for row in build(None) if row[0] in set(skills)]
    catalog_text = render_catalog(catalog_rows)
    catalog_names = {row[0] for row in catalog_rows}
    catalog_hash = hashing.text_hash(catalog_text)
    source_hash = hashing.canonical_json_hash(data)

    tests = []
    for case in data.get("cases", []):
        for rep in range(1, reps + 1):
            tests.append(case_to_test(case, rep, catalog_text, catalog_names,
                                      skills))

    out_path = out_path[:-5] if out_path.endswith(".yaml") else out_path
    if not out_path.endswith(".json"):
        out_path += ".json"
    meta_path = out_path + ".meta.json"
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    meta = {
        "generated_by": "experiments/promptfoo/generators/routing_cases.py",
        "source": os.path.relpath(source_path),
        "source_hash": source_hash,
        "evidence_kind": evidence_kind,
        "catalog_hash": catalog_hash,
        "reps": reps,
        "test_count": len(tests),
    }
    with open(meta_path, "w") as stream:
        json.dump(meta, stream, indent=2)
        stream.write("\n")
    with open(out_path, "w") as stream:
        json.dump(tests, stream, indent=2, ensure_ascii=False)
        stream.write("\n")
    print(f"wrote {out_path} (+ .meta.json): "
          f"{len(data.get('cases', []))} cases x {reps} reps | "
          f"catalog_hash={catalog_hash[:16]} | "
          f"source_hash={source_hash[:16]}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--set", required=True,
                    help="review-family (development) or review-discrim-1 "
                         "(holdout)")
    ap.add_argument("--reps", type=int, default=3)
    ap.add_argument("--out", default=None)
    args = ap.parse_args()
    out = args.out or os.path.join(
        GENERATED_DIR, f"routing-{args.set}-tests.yaml")
    generate(args.set, args.reps, out)


if __name__ == "__main__":
    main()
